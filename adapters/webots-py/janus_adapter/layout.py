"""Segment layout (protocol §3). Mirrors ``coupling_core::layout``; cross-checked in tests against a
vector generated by the Rust reference (``tests/fixtures/layout_vector.json``)."""

from __future__ import annotations

from dataclasses import dataclass
from typing import Dict, Iterable, List

from . import protocol as P

HEADER_SIZE = P.HEADER_SIZE


@dataclass(frozen=True)
class Slot:
    slot_id: int
    entity_id: int
    signal_id: int
    name: str
    value_type: str
    direction: str  # "to_model" | "to_webots"
    frame: str
    unit: str
    required: bool
    enabled: bool
    limits: dict | None
    point: list | None
    validity_offset: int = 0
    value_offset: int = 0

    @property
    def size(self) -> int:
        return P.VALUE_SIZE[self.value_type]


def slots_from_manifest(manifest: dict) -> List[Slot]:
    out = []
    for s in manifest["slots"]:
        out.append(
            Slot(
                slot_id=s["slot_id"],
                entity_id=s["entity_id"],
                signal_id=s["signal_id"],
                name=s["name"],
                value_type=s["value_type"],
                direction=s["direction"],
                frame=s.get("frame", "none"),
                unit=s.get("unit", ""),
                required=bool(s.get("required", False)),
                enabled=bool(s.get("enabled", True)),
                limits=s.get("limits"),
                point=s.get("point"),
            )
        )
    return out


def _place(slots: Iterable[Slot], direction: str, base: int):
    mine = [s for s in slots if s.direction == direction]
    cursor = P.align8(len(mine))
    placed = []
    for i, s in enumerate(mine):
        placed.append(_with_offsets(s, base + i, base + cursor))
        cursor += P.align8(s.size)
    return placed, cursor


def _with_offsets(s: Slot, validity_offset: int, value_offset: int) -> Slot:
    return Slot(**{**s.__dict__, "validity_offset": validity_offset, "value_offset": value_offset})


def place_from_header(slots: Iterable[Slot], header: P.Header) -> List[Slot]:
    """Consumer side: compute every slot's offsets from the region bases found in the header, then
    check the resulting region lengths agree with the header (protocol §6, step 2)."""
    slots = list(slots)
    state_off, state_len = header.region("state_off")
    effort_off, effort_len = header.region("effort_off")
    a, a_len = _place(slots, "to_model", state_off)
    b, b_len = _place(slots, "to_webots", effort_off)
    if a_len != state_len or b_len != effort_len:
        raise P.ProtocolError("manifest slots do not match header region sizes")
    by_id: Dict[int, Slot] = {s.slot_id: s for s in a + b}
    return [by_id[s.slot_id] for s in slots]


def build_layout(slots: Iterable[Slot], manifest_cap: int, hello_cap: int, report_cap: int) -> dict:
    """Host side (used by tests and fake hosts): full layout from scratch."""
    slots = list(slots)
    manifest_off = HEADER_SIZE
    hello_off = P.align8(manifest_off + manifest_cap)
    report_off = P.align8(hello_off + hello_cap)
    state_off = P.align8(report_off + report_cap)
    a, a_len = _place(slots, "to_model", state_off)
    effort_off = P.align8(state_off + a_len)
    b, b_len = _place(slots, "to_webots", effort_off)
    by_id = {s.slot_id: s for s in a + b}
    return {
        "manifest_off": manifest_off,
        "manifest_len": manifest_cap,
        "hello_off": hello_off,
        "hello_len": hello_cap,
        "report_off": report_off,
        "report_len": report_cap,
        "state_off": state_off,
        "state_len": a_len,
        "effort_off": effort_off,
        "effort_len": b_len,
        "total_size": P.align8(effort_off + b_len),
        "state_slot_count": len(a),
        "effort_slot_count": len(b),
        "slots": [by_id[s.slot_id] for s in slots],
    }
