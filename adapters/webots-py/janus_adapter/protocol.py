"""Protocol constants and helpers (docs/01-protocol-v1.md).

Every numeric constant (header offsets, enum values, value sizes) is loaded from
``protocol_offsets.json``, which is generated by the Rust reference
(``cargo run -p coupling-core --example dump_offsets``). Nothing is hand-copied here.
"""

from __future__ import annotations

import json
import os
import struct
from pathlib import Path

_OFFSETS_ENV = "WCP_PROTOCOL_OFFSETS"


def _load() -> dict:
    path = os.environ.get(_OFFSETS_ENV)
    candidates = [Path(path)] if path else []
    here = Path(__file__).resolve().parent
    candidates += [here / "protocol_offsets.json", here.parent / "protocol_offsets.json"]
    for c in candidates:
        if c.is_file():
            return json.loads(c.read_text(encoding="utf-8-sig"))
    raise FileNotFoundError("protocol_offsets.json not found (set %s)" % _OFFSETS_ENV)


_P = _load()

MAGIC: bytes = _P["magic"].encode("ascii")
PROTOCOL_MAJOR, PROTOCOL_MINOR = _P["protocol"]
HEADER_SIZE: int = _P["header_size"]
OFF: dict = _P["header_offsets"]
HS: dict = _P["enums"]["handshake_state"]
VALIDITY: dict = _P["enums"]["validity"]
FRAME: dict = _P["enums"]["frame"]
SYNC_MODE: dict = _P["enums"]["sync_mode"]
VALUE_SIZE: dict = {v["name"]: v["size"] for v in _P["value_types"]}
SIGNALS_BY_NAME: dict = {s["name"]: s for s in _P["signals"]}

VALIDITY_NAME = {v: k for k, v in VALIDITY.items()}
HS_NAME = {v: k for k, v in HS.items()}

# Precompiled little-endian structs (protocol: little-endian, 8-byte aligned).
U32 = struct.Struct("<I")
U64 = struct.Struct("<Q")
I64 = struct.Struct("<q")
F64 = struct.Struct("<d")
V3 = struct.Struct("<3d")
Q4 = struct.Struct("<4d")


class ProtocolError(RuntimeError):
    pass


def segment_names(sim_id: int, instance_id: int, platform: str = "windows") -> dict:
    """Golden object names (protocol §2)."""
    base = "wcp.%016x.%d" % (sim_id, instance_id)
    prefix = "Local\\" if platform == "windows" else "/"
    seg = prefix + base
    return {"segment": seg, "s2m": seg + ".s2m", "m2s": seg + ".m2s"}


def align8(n: int) -> int:
    return (n + 7) & ~7


class Header:
    """Typed accessors over the 256-byte header living at the start of ``buf``.

    ``buf`` is any writable buffer (ctypes array / bytearray). Aligned 8-byte reads and writes through
    ``struct`` are single machine moves on x86-64, which together with x86 TSO gives the acquire/release
    behaviour the protocol needs (the adapter refuses to run on other architectures).
    """

    def __init__(self, buf):
        self.buf = buf

    # -- raw field access --
    def u32(self, name: str) -> int:
        return U32.unpack_from(self.buf, OFF[name])[0]

    def u64(self, name: str) -> int:
        return U64.unpack_from(self.buf, OFF[name])[0]

    def i64(self, name: str) -> int:
        return I64.unpack_from(self.buf, OFF[name])[0]

    def set_u32(self, name: str, v: int) -> None:
        U32.pack_into(self.buf, OFF[name], v)

    def set_u64(self, name: str, v: int) -> None:
        U64.pack_into(self.buf, OFF[name], v)

    def set_i64(self, name: str, v: int) -> None:
        I64.pack_into(self.buf, OFF[name], v)

    # -- derived --
    def validate(self) -> None:
        if bytes(self.buf[OFF["magic"] : OFF["magic"] + 8]) != MAGIC:
            raise ProtocolError("bad segment magic")
        major = struct.unpack_from("<H", self.buf, OFF["protocol_major"])[0]
        if major != PROTOCOL_MAJOR:
            raise ProtocolError("unsupported protocol major %d" % major)
        if self.u32("header_size") != HEADER_SIZE:
            raise ProtocolError("bad header_size")

    @property
    def hs_state(self) -> int:
        return self.u32("hs_state")

    # regions: (offset, length) pairs live at consecutive u64s: *_off then *_len
    def region(self, name: str):
        off = OFF[name]
        return U64.unpack_from(self.buf, off)[0], U64.unpack_from(self.buf, off + 8)[0]
